function resolvePlaywright() {
  for (const candidate of [
    path.join(root, "node_modules", "playwright"),
    "C:/git-app/survey-workflow-orchestrator/node_modules/playwright",
  ]) {
    try { return require(candidate); } catch { /* next */ }
  }
  throw new Error("Playwright is required to render the stage series.");
}

function run(command, args, options = {}) {
  const result = spawnSync(command, args, { cwd: root, stdio: "inherit", shell: false, ...options });
  if (result.status !== 0) throw new Error(`${command} failed (${result.status})`);
}

function capture(command, args) {
  const result = spawnSync(command, args, { cwd: root, encoding: "utf8", shell: false });
  if (result.status !== 0) throw new Error(result.stderr || `${command} failed`);
  return result.stdout.trim();
}

function duration(file) {
  return Number(capture("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "default=nw=1:nk=1", file]));
}

function escapeHtml(value) {
  return String(value).replaceAll("&", "&amp;").replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;").replaceAll('"', "&quot;");
}

function dataUrl(file) {
  return `data:image/png;base64,${fs.readFileSync(file).toString("base64")}`;
}

