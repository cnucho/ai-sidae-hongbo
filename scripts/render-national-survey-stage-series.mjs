function narration(episode, topic, index) {
  const [heading, evidence] = topic;
  const transitions = [
    "Begin by orienting yourself to the screen before taking action.",
    "Notice that the current project, stage, and recommended application remain connected.",
    "The important point is that this state was produced by the running application.",
    "Read the visible status and next action before deciding whether to continue.",
    "This step protects the handoff to the next production team.",
    "Use the application evidence rather than assuming that a successful click means completion.",
    "At the end of this step, confirm the next action shown by the project hub.",
  ];
  return `${heading}. ${evidence} ${transitions[index]} In practice, pause here and check the project title, production preset, current stage, worker message, and recommended app. If the expected state or receipt is missing, do not continue the survey workflow. Resolve the application issue, rerun the same step, and keep the resulting receipt with the project. This is how the system preserves traceability from one team to the next.`;
}

