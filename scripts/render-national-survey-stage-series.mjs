const { chromium } = resolvePlaywright();
const browser = await chromium.launch({ headless: true });
const reports = [];

try {
  for (const episode of episodes) {
    const episodeRoot = path.join(workRoot, episode.id);
    const slideRoot = path.join(episodeRoot, "slides");
    const narrationRoot = path.join(episodeRoot, "narration");
    const audioRoot = path.join(episodeRoot, "audio");
    const clipRoot = path.join(episodeRoot, "clips");
    await Promise.all([slideRoot, narrationRoot, audioRoot, clipRoot].map((dir) => mkdir(dir, { recursive: true })));
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
    const rendered = [];

    for (let index = 0; index < episode.topics.length; index += 1) {
      const id = String(index + 1).padStart(2, "0");
      const slidePath = path.join(slideRoot, `${id}.png`);
      const textPath = path.join(narrationRoot, `${id}.txt`);
      const audioPath = path.join(audioRoot, `${id}.wav`);
      const clipPath = path.join(clipRoot, `${id}.mp4`);
      await page.setContent(slideHtml(episode, episode.topics[index], episode.screens[index], index), { waitUntil: "load" });
      await page.screenshot({ path: slidePath });
      await writeFile(textPath, `${narration(episode, episode.topics[index], index)}\n`, "utf8");
      run("node", ["scripts/synthesize-speech.mjs", "--input", textPath, "--output", audioPath], {
        env: { ...process.env, PR_STUDIO_TTS_PROVIDER_EN: "openai", PR_STUDIO_TTS_LANGUAGE: "en" },
      });
      const audioDuration = duration(audioPath);
      const clipDuration = Math.max(43, audioDuration + 1.2);
      run("ffmpeg", ["-y", "-loglevel", "error", "-loop", "1", "-i", slidePath, "-i", audioPath,
        "-filter_complex", `[1:a]apad=pad_dur=${clipDuration.toFixed(3)}[a]`, "-map", "0:v", "-map", "[a]",
        "-t", clipDuration.toFixed(3), "-r", "24", "-c:v", "libx264", "-preset", "veryfast", "-crf", "23",
        "-pix_fmt", "yuv420p", "-c:a", "aac", "-b:a", "160k", clipPath]);
      rendered.push({ id, topic: episode.topics[index][0], sourceScreen: episode.screens[index], audioDuration, clipDuration });
    }
    await page.close();
    const concatPath = path.join(episodeRoot, "concat.txt");
    await writeFile(concatPath, rendered.map((item) => `file '${path.join(clipRoot, `${item.id}.mp4`).replaceAll("\\", "/")}'`).join("\n") + "\n");
    const finalPath = path.join(outRoot, `${episode.id}.mp4`);
    run("ffmpeg", ["-y", "-loglevel", "error", "-f", "concat", "-safe", "0", "-i", concatPath,
      "-c:v", "libx264", "-preset", "veryfast", "-crf", "23", "-pix_fmt", "yuv420p",
      "-c:a", "aac", "-b:a", "160k", "-movflags", "+faststart", finalPath]);
    const finalDuration = duration(finalPath);
    if (finalDuration < 300 || finalDuration > 600) throw new Error(`${episode.id} duration ${finalDuration} is outside 5–10 minutes.`);
    const samplePath = path.join(outRoot, `${episode.id}-sample.png`);
    run("ffmpeg", ["-y", "-loglevel", "error", "-i", finalPath, "-ss", (finalDuration * .58).toFixed(2), "-frames:v", "1", samplePath]);
    reports.push({ id: episode.id, title: episode.title, finalPath, samplePath, duration: finalDuration, fileSize: fs.statSync(finalPath).size, beats: rendered });
  }
} finally {
  await browser.close();
}

